#!/usr/bin/env python3
"""Regenerate the apps' launcher icon foregrounds (the Layers marks).

Usage: python3 scripts/launcher_icons.py   (needs shapely: pip install shapely)
Each mark is a pale shape behind a white one. The shapes are built and cut with shapely, so the
pale layer stops where the white one starts and holes in the white one show the background.
Vector drawables have no masks or boolean operations, so the results are written out as plain paths.
"""
import math
from pathlib import Path
from shapely.geometry import LineString, Point, Polygon, box
from shapely.affinity import rotate, translate, scale

REPO = Path(__file__).resolve().parent.parent
SCALE = 0.8  # the symbol's size within the icon, around its centre
Q = 24       # segments per quarter circle

def rrect(x, y, w, h, r):
    return box(x + r, y + r, x + w - r, y + h - r).buffer(r, quad_segs=Q)

def place(shape):
    return scale(shape, SCALE, SCALE, origin=(54, 54))

def path(shape):
    polys = getattr(shape, "geoms", [shape])
    parts = []
    for p in polys:
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            parts.append("M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z")
    return "\n                ".join(parts)

def vector(comment, layers):
    body = "\n".join(f'''    <path
        android:fillAlpha="{alpha}"
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"
        android:pathData="{path(place(shape))}" />''' for shape, alpha in layers)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by scripts/launcher_icons.py, which explains the shapes; edit it there. Within the 66dp adaptive-icon safe zone;
     also the monochrome layer for themed icons. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
'''

def write(app, comment, layers):
    p = REPO / f"apps/{app}/src/main/res/drawable/ic_launcher_foreground.xml"
    p.write_text(vector(comment, layers))
    print("wrote", p)

# Tasks: a ticked box in front of another.
front = rrect(31, 40, 38, 38, 10)
tick = LineString([(41.5, 56), (48.5, 63), (61, 50.5)]).buffer(3, quad_segs=Q)
write("tasks", "The Range Tasks mark: a ticked box in front of another, a range of them.",
      [(rrect(41, 30, 38, 38, 10).difference(front), 0.45), (front.difference(tick), 1)])

# Lift: a dumbbell on the diagonal, the outer plates paler, behind the inner ones.
def turned(s):
    return rotate(s, -45, origin=(54, 54))
inner = turned(box(38, 51, 70, 57).union(rrect(32, 35, 9, 38, 4.5)).union(rrect(67, 35, 9, 38, 4.5)))
outer = turned(rrect(26, 40, 7, 28, 3.5).union(rrect(75, 40, 7, 28, 3.5)))
write("lift", "The Range Lift mark: a dumbbell on the diagonal, its outer plates paler, stacked behind the inner ones.",
      [(outer.difference(inner), 0.5), (inner, 1)])

# Notes: one sticky note on another, with two lines written on it and its corner lifting.
note = rrect(0, 0, 38, 38, 7).intersection(Polygon([(-1, -1), (39, -1), (39, 25), (25, 39), (-1, 39)]))
arc = [(30 - 4 * math.cos(math.radians(a)), 30 - 4 * math.sin(math.radians(a))) for a in range(0, 91, 5)]
crease = LineString([(26, 40), *arc, (40, 26)]).buffer(1.3, cap_style="flat", quad_segs=Q)
lines = rrect(8, 12, 22, 4.5, 2.25).union(rrect(8, 21, 14, 4.5, 2.25))
def front_place(s):
    return translate(rotate(s, -5, origin=(19, 19)), 29, 37)
front_note = front_place(note)
back_note = translate(rotate(rrect(0, 0, 38, 38, 7), 12, origin=(19, 19)), 42, 27)
write("notes", "The Range Notes mark: a sticky note on top of another, with two lines on it and its corner lifting.",
      [(back_note.difference(front_note), 0.45), (front_place(note.difference(lines).difference(crease)), 1)])

# Calculator: a round key with "=" on it, in front of another.
key = Point(50, 58).buffer(19, quad_segs=Q)
equals = rrect(41, 49, 18, 5, 2.5).union(rrect(41, 60, 18, 5, 2.5))
write("calc", "The Range Calculator mark: a round key with = on it, in front of another.",
      [(Point(62, 46).buffer(16, quad_segs=Q).difference(key), 0.45), (key.difference(equals), 1)])
