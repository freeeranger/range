#!/usr/bin/env python3
"""Regenerate range-ui's RangeIcons.kt from Material Symbols.

Usage: python3 -I scripts/icons.py
Reads symbol names from range-ui/icons.txt (one per line, e.g. "arrow_back"), downloads each
one's Android vector from Google's material-design-icons repository (Rounded style, 24dp,
weight 400) and writes its path data out as a Compose ImageVector.
"""

import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = ROOT / "range-ui" / "icons.txt"
OUT = ROOT / "range-ui/src/main/kotlin/dev/freeranger/range/ui/icons/RangeIcons.kt"
STYLE = "materialsymbolsrounded"
SOURCE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android/{name}/{style}/{name}_24px.xml"
ANDROID = "{http://schemas.android.com/apk/res/android}"


def kotlin_name(name):
    return "".join(part.capitalize() for part in name.split("_"))


def main():
    names = [n.strip() for n in NAMES.read_text().splitlines() if n.strip() and not n.startswith("#")]
    entries = []
    for name in sorted(set(names)):
        with urllib.request.urlopen(SOURCE.format(name=name, style=STYLE)) as response:
            vector = ET.fromstring(response.read())
        if vector.get(f"{ANDROID}viewportWidth") != "960":
            raise ValueError(f"{name}: expected a 960 viewport")
        paths = [p.get(f"{ANDROID}pathData") for p in vector.iter("path")]
        args = ", ".join(f'"{p}"' for p in paths)
        entries.append(f'    val {kotlin_name(name)} by lazy {{ symbol("{name}", {args}) }}')
        print(f"  {name}", file=sys.stderr)

    OUT.write_text(TEMPLATE.replace("ENTRIES", "\n".join(entries)))
    print(f"wrote {len(entries)} icons to {OUT.relative_to(ROOT)}", file=sys.stderr)


TEMPLATE = '''package dev.freeranger.range.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

// Generated by scripts/icons.py from range-ui/icons.txt. Do not edit by hand.

/**
 * Material Symbols, Rounded style (Apache 2.0, see the licences screen): the standard icons for
 * Material You apps. Material's Icon() tints them, so the fill colour here is irrelevant.
 */
object RangeIcons {
ENTRIES
}

private fun symbol(name: String, vararg paths: String): ImageVector =
    ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 960f, viewportHeight = 960f)
        .apply { paths.forEach { addPath(pathData = addPathNodes(it), fill = SolidColor(Color.Black)) } }
        .build()
'''

if __name__ == "__main__":
    main()
